def enemy_image_path(floor, name, is_boss=False):
    """登録画像がある敵だけstatic配信用の相対パスを返す。"""
    prefix = f"{floor}_boss_" if is_boss else f"{floor}_"
    stem = f"{prefix}{name}"
    if stem not in AVAILABLE_ICON_STEMS:
        return None
    return f"images/enemies/{stem}.png"
